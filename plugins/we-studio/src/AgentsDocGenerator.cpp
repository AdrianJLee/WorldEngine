#include "AgentsDocGenerator.h"
#include "World/Utils/Paths.h"

#include <filesystem>
#include <fstream>
#include <sstream>

namespace World::Studio
{
	namespace fs = std::filesystem;

	std::string AgentsDocGenerator::Generate(const StudioPolicy& policy)
	{
		std::ostringstream ss;
		ss << "# Project Agent Guidelines (Generated by WorldEngine Studio)\n\n";
		ss << "## 1. Core Rule: No Direct Bypasses\n";
		ss << "- All file and scene modifications MUST be performed through the `we-mcp` or `we-ai-assistant` channels.\n";
		ss << "- Direct out-of-channel edits will be flagged as unattributed modifications and will block gate advancement.\n";
		ss << "- The engine source tree (Engine/, Editor/, Runtime/) is strictly read-only.\n\n";

		ss << "## 2. Active Roles and Responsibilities\n";
		for (const auto& kv : policy.GetRoles())
		{
			const auto& r = kv.second;
			if (r.disabled) continue;

			ss << "### Role: `" << r.id << "` (" << r.name << ")\n";
			ss << "- **Tier**: " << r.tier << " | **Department**: " << r.department << " | **Kind**: " << r.kind << "\n";
			if (!r.duties.empty())
			{
				ss << "- **Duties**: ";
				for (size_t i = 0; i < r.duties.size(); ++i)
				{
					if (i) ss << ", ";
					ss << r.duties[i];
				}
				ss << "\n";
			}
			if (!r.write.empty())
			{
				ss << "- **Write Scope**: ";
				for (size_t i = 0; i < r.write.size(); ++i)
				{
					if (i) ss << ", ";
					ss << "`" << r.write[i] << "`";
				}
				ss << "\n";
			}
			ss << "\n";
		}

		return ss.str();
	}

	bool AgentsDocGenerator::WriteToProject(const std::string& projectRoot, const StudioPolicy& policy)
	{
		const fs::path root = fs::u8path(projectRoot.empty() ? Paths::ProjectDir().string() : projectRoot);
		if (!fs::exists(root))
			return false;

		const std::string text = Generate(policy);

		std::ofstream f1(root / "AGENTS.md");
		if (f1) f1 << text;

		std::ofstream f2(root / "CLAUDE.md");
		if (f2) f2 << text;

		return true;
	}
}
